#!/usr/bin/env python3
"""Regenerate the sibling-build tables kept under references/ for unit-split work.

    python3 tools/sibling_tables.py nascar-units
        references/NASCAR 2005/DOL-GN4E-USA/symbols/compile_units.tsv, from the committed
        symbols.tsv and elf_sections.tsv of NASCAR 2005's DWARF build: one row per compile unit
        with its .text start, end and size, in link order.
    python3 tools/sibling_tables.py ps2-map --ps2 DIR
        references/NFL Street 2/SLUS-21118/gc-to-ps2-functions.tsv: this target's functions paired
        with the PS2 release's (SLUS_211.18). DIR holds the private SLUS_211.18 and its
        elf-metadata.json (the build repository's reference/ps2/slus_211_18); the original is read
        from orig/<target>/sys/main.dol and the function extents from evidence.tsv.

Both write a header of `#` lines naming this script's hash and every input's hash, so a table can be
traced to the run that made it. `--check` compares instead of writing and exits 1 on a difference.

NASCAR units: a type-4 symbol names a source file; the `gcc2_compiled.` label that follows it is the
start of that file's .text (ProDG emits one per GCC compile unit). Each unit ends where the next one
starts, or at the end of .text. 71 files have functions but no `gcc2_compiled.` row in the export;
for them the start is the lowest listed function (`start_from` = first-function), so the true start
is at or before it and the unit before it may hold some of its code. Files with no code are left out.
`functions` counts the function symbols (local and global) the export places in the unit's range.

GC-to-PS2 map, the method of the 2026-10-24 second look (call-graph propagation from strings):
1. Seeds: a printable string (4+ characters) that exactly one GC function and exactly one PS2 function
   load votes 3 for that pair; a string loaded by the same number of functions (up to 6) on both
   sides votes 1 for each pair in address order. A function keeps its top pair at 2+ votes or when it
   has one candidate.
2. Propagation, up to 30 rounds: each mapped pair votes for its callees in call order when both call
   lists have the same length, else for the distinct callees in order when those counts agree; a
   callee takes a pair that is unanimous or at least twice the runner-up. Then a gap between two
   mapped functions whose index distance is the same on both sides is filled in order.
GC functions are the evidence.tsv `function` rows; PS2 functions start at jal targets, 8-aligned text
pointers in .data/.rodata/.sdata and lui/addiu pairs, and end at the next start. The pairs are
`related` evidence: a candidate for "PS2 shape" checks and split work, not proof of a name or extent.
"""
import argparse
import collections
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGET = 'GN7E69-rev0'
NASCAR = ROOT / 'references/NASCAR 2005/DOL-GN4E-USA/symbols'
PS2_MAP = ROOT / 'references/NFL Street 2/SLUS-21118/gc-to-ps2-functions.tsv'
R13 = 0x803F22A0  # This target's _SDA_BASE_ (config/<target>/baseline.json sda_base).
PS2_GP = 0x513AF0


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def header(inputs):
    lines = [f'# Generated by tools/sibling_tables.py (sha256 {sha256((ROOT / "tools/sibling_tables.py").read_bytes())})']
    lines += [f'# input {name} sha256 {digest}' for name, digest in inputs]
    return '\n'.join(lines) + '\n'


# NASCAR 2005 compile units -------------------------------------------------------------------

def nascar_units():
    sections = {row[0]: row for row in (line.split('\t') for line in (NASCAR / 'elf_sections.tsv').read_text().splitlines()[1:])}
    text_start, text_end = int(sections['.text'][2], 16), int(sections['.text'][2], 16) + int(sections['.text'][4])
    files, current, functions = [], None, set()
    lines = [line.split('\t') for line in (NASCAR / 'symbols.tsv').read_text().splitlines()[1:]]
    last_file = max(i for i, row in enumerate(lines) if row[2] == '4')
    # ELF lists local symbols file by file, then every global; the globals begin at __start.
    globals_from = next(i for i, row in enumerate(lines) if i > last_file and row[3] == '__start')
    for number, (address, size, kind, name) in enumerate(lines):
        if kind == '2' and text_start <= int(address, 16) < text_end:
            functions.add(int(address, 16))
        if number >= globals_from:
            continue
        if kind == '4':
            current = {'file': name, 'gcc': None, 'functions': []}
            files.append(current)
            continue
        address = int(address, 16)
        if current is None or not text_start <= address < text_end:
            continue
        if name == 'gcc2_compiled.':
            current['gcc'] = address if current['gcc'] is None else current['gcc']
        elif kind == '2':
            current['functions'].append(address)
    units = []
    for order, entry in enumerate(files):
        if entry['gcc'] is not None:
            units.append((entry['gcc'], order, entry['file'], 'gcc2_compiled'))
        elif entry['functions']:
            units.append((min(entry['functions']), order, entry['file'], 'first-function'))
    units.sort()
    rows = ['start\tend\tsize\tfile\tstart_from\tfunctions']
    for index, (start, _, name, origin) in enumerate(units):
        end = units[index + 1][0] if index + 1 < len(units) else text_end
        count = sum(start <= f < end for f in functions)
        rows.append(f'0x{start:08X}\t0x{end:08X}\t{end - start}\t{name}\t{origin}\t{count}')
    inputs = [(f'references/NASCAR 2005/DOL-GN4E-USA/symbols/{name}', sha256((NASCAR / name).read_bytes()))
              for name in ('symbols.tsv', 'elf_sections.tsv')]
    return NASCAR / 'compile_units.tsv', header(inputs) + '\n'.join(rows) + '\n'


# GC side --------------------------------------------------------------------------------------

class Dol:
    def __init__(self, data):
        self.data, self.segments = data, []
        for i in range(18):
            offset, address, size = (struct.unpack_from('>I', data, base + i * 4)[0] for base in (0, 0x48, 0x90))
            if size:
                self.segments.append((address, size, offset))

    def read(self, address, size):
        for start, length, offset in self.segments:
            if start <= address and address + size <= start + length:
                return self.data[offset + address - start:offset + address - start + size]
        return None


def cstring(read, address):
    """The printable NUL-terminated string at address (up to 300 characters), or None."""
    out = bytearray()
    while True:
        byte = read(address + len(out), 1)
        if byte is None:
            return None
        if byte[0] == 0:
            return out.decode()
        if not (32 <= byte[0] < 127 or byte[0] in (9, 10, 13)):
            return None
        out.append(byte[0])
        if len(out) > 300:
            return out.decode()


def gc_function(dol, start, end):
    """(calls, data references) of one GC function: bl targets, and addresses formed by lis plus
    addi/addic/ori or a D-form displacement, or by r13 (small data) plus a displacement."""
    code = dol.read(start, end - start) or b''
    high, calls, references = {}, [], []
    for at in range(0, len(code) - 3, 4):
        word = struct.unpack_from('>I', code, at)[0]
        opcode, d, a, immediate = word >> 26, (word >> 21) & 31, (word >> 16) & 31, word & 0xFFFF
        signed = immediate - 0x10000 if immediate & 0x8000 else immediate
        if opcode == 18 and word & 1:
            offset = word & 0x3FFFFFC
            calls.append((start + at + (offset - 0x4000000 if offset & 0x2000000 else offset)) & 0xFFFFFFFF)
        elif opcode == 15 and a == 0:  # lis
            high[d] = immediate << 16
        elif opcode in (12, 14, 24):  # addic, addi, ori
            source = d if opcode == 24 else a
            if opcode == 14 and a == 0:
                continue  # li
            if source in high:
                references.append((high[source] + (immediate if opcode == 24 else signed)) & 0xFFFFFFFF)
            elif opcode == 14 and a == 13:
                references.append((R13 + signed) & 0xFFFFFFFF)
        elif 32 <= opcode <= 55 and a:
            if a in high:
                references.append((high[a] + signed) & 0xFFFFFFFF)
            elif a == 13:
                references.append((R13 + signed) & 0xFFFFFFFF)
    return calls, references


# PS2 side -------------------------------------------------------------------------------------

PS2_MEMORY = {0x09, 0x0D, 0x20, 0x21, 0x23, 0x24, 0x25, 0x27, 0x28, 0x29, 0x2B, 0x31, 0x39, 0x37, 0x3F, 0x1E, 0x1F}


class Ps2:
    def __init__(self, directory):
        self.data = (directory / 'SLUS_211.18').read_bytes()
        meta = json.loads((directory / 'elf-metadata.json').read_text())
        self.sections = [(s['name'], int(s['address'], 16), s['size'], int(s['offset'], 16))
                         for s in meta['sections'] if s['type'] == 1 and int(s['address'], 16)]
        self.texts = [s for s in self.sections if s[0] == '.text']

    def read(self, address, size):
        for _, start, length, offset in self.sections:
            if start <= address and address + size <= start + length:
                return self.data[offset + address - start:offset + address - start + size]
        return None

    def in_text(self, address):
        return any(start <= address < start + length for _, start, length, _ in self.texts)

    def functions(self):
        starts = set()
        for _, start, length, offset in self.texts:
            for at in range(0, length, 4):
                word = struct.unpack_from('<I', self.data, offset + at)[0]
                if word >> 26 == 3:
                    starts.add(((start + at + 4) & 0xF0000000) | ((word & 0x3FFFFFF) << 2))
        for name, start, length, offset in self.sections:
            if name in ('.data', '.rodata', '.sdata'):
                for at in range(0, length - 3, 4):
                    value = struct.unpack_from('<I', self.data, offset + at)[0]
                    if value % 8 == 0 and self.in_text(value):
                        starts.add(value)
        for _, start, length, offset in self.texts:
            high = {}
            for at in range(0, length, 4):
                word = struct.unpack_from('<I', self.data, offset + at)[0]
                opcode, rs, rt, immediate = word >> 26, (word >> 21) & 31, (word >> 16) & 31, word & 0xFFFF
                signed = immediate - 0x10000 if immediate & 0x8000 else immediate
                if opcode == 0x0F:
                    high[rt] = (immediate << 16, start + at)
                    continue
                if opcode in PS2_MEMORY and rs in high and start + at - high[rs][1] < 0x400:
                    value = (high[rs][0] + (immediate if opcode == 0x0D else signed)) & 0xFFFFFFFF
                    if value % 8 == 0 and self.in_text(value):
                        starts.add(value)
            starts.add(start)
        starts = sorted(s for s in starts if self.in_text(s))
        result = []
        for index, start in enumerate(starts):
            end = starts[index + 1] if index + 1 < len(starts) else start + 4
            for _, section, length, _ in self.texts:
                if section <= start < section + length:
                    end = min(end, section + length)
            code, calls, references, high = self.read(start, end - start), [], [], {}
            for at in range(0, len(code), 4):
                word = struct.unpack_from('<I', code, at)[0]
                opcode, rs, rt, immediate = word >> 26, (word >> 21) & 31, (word >> 16) & 31, word & 0xFFFF
                signed = immediate - 0x10000 if immediate & 0x8000 else immediate
                if opcode == 3:
                    calls.append(((start + at + 4) & 0xF0000000) | ((word & 0x3FFFFFF) << 2))
                elif opcode == 0x0F:
                    high[rt] = immediate << 16
                elif opcode in PS2_MEMORY:
                    if rs in high:
                        references.append((high[rs] + (immediate if opcode == 0x0D else signed)) & 0xFFFFFFFF)
                    elif rs == 28:
                        references.append((PS2_GP + signed) & 0xFFFFFFFF)
            result.append((start, end, calls, references))
        return result


def ps2_map(directory):
    original = ROOT / 'orig' / TARGET / 'sys/main.dol'
    dol = Dol(original.read_bytes())
    ps2 = Ps2(directory)
    extents = sorted((int(row[1], 16), int(row[2], 16)) for row in
                     (line.split('\t') for line in (ROOT / f'config/{TARGET}/evidence.tsv').read_text().splitlines()[1:])
                     if row[0] == 'function')
    gc = [(start, end, *gc_function(dol, start, end)) for start, end in extents]
    pf = ps2.functions()
    gc_index = {g[0]: i for i, g in enumerate(gc)}
    ps_index = {p[0]: i for i, p in enumerate(pf)}

    def strings(read, references):
        found = []
        for target in references:
            text = cstring(read, target)
            if text and len(text) >= 4:
                found.append(text)
        return found

    gc_strings, ps_strings = collections.defaultdict(set), collections.defaultdict(set)
    for i, g in enumerate(gc):
        for text in strings(dol.read, g[3]):
            gc_strings[text].add(i)
    for i, p in enumerate(pf):
        for text in strings(ps2.read, p[3]):
            ps_strings[text].add(i)
    pairs, votes = {}, collections.defaultdict(collections.Counter)
    for text in gc_strings:
        if text in ps_strings and len(gc_strings[text]) == 1 and len(ps_strings[text]) == 1:
            votes[next(iter(gc_strings[text]))][next(iter(ps_strings[text]))] += 3
        elif text in ps_strings and len(gc_strings[text]) == len(ps_strings[text]) <= 6:
            for a, b in zip(sorted(gc_strings[text]), sorted(ps_strings[text])):
                votes[a][b] += 1
    for a, counter in votes.items():
        b, count = counter.most_common(1)[0]
        if count >= 2 or len(counter) == 1:
            pairs[a] = b

    def callees(functions, index, i):
        return [index.get(t) if index.get(t) != i else 'self' for t in functions[i][2]]

    for _ in range(30):
        new = collections.defaultdict(collections.Counter)
        for a, b in list(pairs.items()):
            gc_calls = [x for x in callees(gc, gc_index, a) if x != 'self']
            ps_calls = [y for y in callees(pf, ps_index, b) if y != 'self']
            if len(gc_calls) == len(ps_calls):
                for x, y in zip(gc_calls, ps_calls):
                    if x is not None and y is not None:
                        new[x][y] += 1
            else:
                gc_distinct = list(dict.fromkeys(x for x in gc_calls if x is not None))
                ps_distinct = list(dict.fromkeys(y for y in ps_calls if y is not None))
                if len(gc_distinct) == len(ps_distinct):
                    for x, y in zip(gc_distinct, ps_distinct):
                        new[x][y] += 1
        added = 0
        for x, counter in new.items():
            if x in pairs:
                continue
            y, count = counter.most_common(1)[0]
            if count >= 1 and (len(counter) == 1 or count >= 2 * counter.most_common(2)[1][1]):
                pairs[x] = y
                added += 1
        keys = sorted(pairs)
        for k1, k2 in zip(keys, keys[1:]):
            if k2 - k1 > 1 and pairs[k2] - pairs[k1] == k2 - k1:
                for step in range(1, k2 - k1):
                    if k1 + step not in pairs:
                        pairs[k1 + step] = pairs[k1] + step
                        added += 1
        if not added:
            break
    rows = ['gc_start\tgc_end\tps2_start\tps2_end']
    for a in sorted(pairs):
        g, p = gc[a], pf[pairs[a]]
        rows.append(f'0x{g[0]:08X}\t0x{g[1]:08X}\t0x{p[0]:X}\t0x{p[1]:X}')
    inputs = [(f'orig/{TARGET}/sys/main.dol', sha256(original.read_bytes())),
              ('SLUS_211.18', sha256(ps2.data)),
              (f'config/{TARGET}/evidence.tsv', sha256((ROOT / f'config/{TARGET}/evidence.tsv').read_bytes()))]
    return PS2_MAP, header(inputs) + '\n'.join(rows) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('table', choices=('nascar-units', 'ps2-map'))
    parser.add_argument('--ps2', type=Path, help='folder with the private SLUS_211.18 and elf-metadata.json')
    parser.add_argument('--check', action='store_true', help='compare with the committed table instead of writing')
    args = parser.parse_args()
    if args.table == 'ps2-map' and args.ps2 is None:
        parser.error('ps2-map needs --ps2')
    path, text = nascar_units() if args.table == 'nascar-units' else ps2_map(args.ps2)
    if args.check:
        same = path.is_file() and path.read_text() == text
        print(f"{path.relative_to(ROOT)}: {'up to date' if same else 'differs; run without --check to rewrite it'}")
        return 0 if same else 1
    path.write_text(text)
    rows = sum(1 for line in text.splitlines() if not line.startswith('#')) - 1
    print(f'{path.relative_to(ROOT)}: {rows} rows')
    return 0


if __name__ == '__main__':
    sys.exit(main())
