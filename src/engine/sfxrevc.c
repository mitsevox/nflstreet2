float *MIX_getwetbuffer(int index)
{
    return sndfx.m0[index];
}

void MIX_createFxglobals(void)
{
    int size = lbl_8030002C * sizeof(float *) + lbl_8030002C * sizeof(int) + lbl_8030002C * sizeof(float);
    float **buffer = (float **)SNDMEMI_allocz(size);

    sndfx.m0 = buffer;
    sndmix.m14 = (int *)(buffer + lbl_8030002C);
    sndmix.m100 = (float *)(sndmix.m14 + lbl_8030002C);
    memset(buffer, 0, size);
    fxBusesLinkList = (Node_803B4E20 **)SNDMEMI_allocz(lbl_8030002C * 4);
    memset(fxBusesLinkList, 0, lbl_8030002C * 4);
    fxGlobalsCreated = 1;
}

void MIX_destroyFxglobals(void)
{
    int i;

    if (fxGlobalsCreated != 0) {
        SNDMEMI_free(sndfx.m0);
        for (i = 0; i < lbl_8030002C; i++) {
            if (fxBusesLinkList[i] != 0) {
                Node_803B4E20 *node = fxBusesLinkList[i];

                do {
                    Node_803B4E20 *next = node->m0;

                    SNDMEMI_free(node);
                    node = next;
                } while (node != 0);
            }
        }
        SNDMEMI_free(fxBusesLinkList);
        fxGlobalsCreated = 0;
    }
}
