#define YUV_PACK(y0, u, y1, v) (((y0) << 24) | ((u) << 16) | ((y1) << 8) | (v))

static inline void _YuvConvertLine(u32 *line, u8 *y, u8 *u, u8 *v, int n)
{
    int x = 0;
    u32 *d;
    u8 *up;
    u8 *vp;

    while (x < n && ((u32)line & 15)) {
        line[x] = YUV_PACK(y[x * 2], u[x], y[x * 2 + 1], v[x]);
        x++;
    }
    if (x <= n) {
        GXRedirectWriteGatherPipe(line);
        d = line + x;
        up = u + x;
        vp = v + x;
        goto test;
        do {
            *d++ = YUV_PACK(y[x * 2], *up, y[x * 2 + 1], *vp);
            x++;
            up++;
            vp++;
        test:
            while (x + 8 < n) {
                GXWGFifo.u32 = YUV_PACK(y[x * 2 + 0], up[0], y[x * 2 + 1], vp[0]);
                GXWGFifo.u32 = YUV_PACK(y[x * 2 + 2], up[1], y[x * 2 + 3], vp[1]);
                GXWGFifo.u32 = YUV_PACK(y[x * 2 + 4], up[2], y[x * 2 + 5], vp[2]);
                GXWGFifo.u32 = YUV_PACK(y[x * 2 + 6], up[3], y[x * 2 + 7], vp[3]);
                GXWGFifo.u32 = YUV_PACK(y[x * 2 + 8], up[4], y[x * 2 + 9], vp[4]);
                GXWGFifo.u32 = YUV_PACK(y[x * 2 + 10], up[5], y[x * 2 + 11], vp[5]);
                GXWGFifo.u32 = YUV_PACK(y[x * 2 + 12], up[6], y[x * 2 + 13], vp[6]);
                GXWGFifo.u32 = YUV_PACK(y[x * 2 + 14], up[7], y[x * 2 + 15], vp[7]);
                d += 8;
                up += 8;
                vp += 8;
                x += 8;
            }
        } while (x < n);
        GXRestoreWriteGatherPipe();
    }
}

int YUV_convert(u8 **planes, int x, int y, int pitch, int width, int height, int frameBuffer)
{
    int j;
    int n = width >> 1;
    int stride = pitch << 1;
    u8 *base = (u8 *)(frameBuffer + 0x40000000);

    for (j = 0; j < height / 2; j++) {
        u8 *line = base + y * stride + (x << 1) + j * stride * 2;
        u8 *yp = planes[0] + width * j;
        u8 *up = planes[1] + (j >> 1) * n;
        u8 *vp = planes[2] + (j >> 1) * n;

        _YuvConvertLine((u32 *)line, yp, up, vp, n);
        _YuvConvertLine((u32 *)(line + stride), yp, up, vp, n);
    }
    return 0;
}

int YUV_convert_noscale(u8 **planes, int x, int y, int pitch, int width, int height, int frameBuffer)
{
    int j;
    int n = width >> 1;
    int stride = pitch << 1;
    u8 *base = (u8 *)(frameBuffer + 0x40000000);

    for (j = 0; j < height; j++) {
        u8 *line = base + y * stride + (x << 1) + j * stride;
        u8 *yp = planes[0] + width * j;
        u8 *up = planes[1] + (j >> 1) * n;
        u8 *vp = planes[2] + (j >> 1) * n;

        _YuvConvertLine((u32 *)line, yp, up, vp, n);
    }
    return 0;
}

static inline u8 _YuvClamp(int c)
{
    if (c < 0) {
        return 0;
    }
    if (c > 255) {
        return 255;
    }
    return c;
}

static inline void _YuvLutAddR(YuvLut_t *d, YuvLut_t *s)
{
    d->r += s->r;
}

static inline void _YuvLutAddRGB(YuvLut_t *d, YuvLut_t *s)
{
    d->r += s->r;
    d->g += s->g;
    d->b += s->b;
}

static inline void _YuvLutAddARGB(YuvLut_t *d, YuvLut_t *s)
{
    d->a += s->a;
    d->r += s->r;
    d->g += s->g;
    d->b += s->b;
}

void yuvtoRGB32_C(u8 *y, u8 *u, u8 *v, u8 *dst, u8 *end)
{
    YuvLut_t cu;
    YuvLut_t cv;
    YuvLut_t p0;
    YuvLut_t p1;

    while (dst < end) {
        cu = lutcb[*u++];
        cv = lutcr[*v++];
        _YuvLutAddRGB(&cu, &cv);
        p0 = luty[y[0]];
        p1 = luty[y[1]];
        y += 2;
        _YuvLutAddRGB(&p0, &cu);
        _YuvLutAddRGB(&p1, &cu);
        dst[0] = _YuvClamp(p0.b);
        dst[1] = _YuvClamp(p0.g);
        dst[2] = _YuvClamp(p0.r);
        dst[4] = _YuvClamp(p1.b);
        dst[5] = _YuvClamp(p1.g);
        dst[6] = _YuvClamp(p1.r);
        dst += 8;
    }
}

void yuvtoA32_C(u8 *y, u8 *u, u8 *v, u8 *dst, u8 *end)
{
    YuvLut_t cu;
    YuvLut_t cv;
    YuvLut_t p0;
    YuvLut_t p1;

    while (dst < end) {
        cu = lutcb[*u++];
        cv = lutcr[*v++];
        _YuvLutAddR(&cu, &cv);
        p0 = luty[y[0]];
        p1 = luty[y[1]];
        y += 2;
        _YuvLutAddR(&p0, &cu);
        _YuvLutAddR(&p1, &cu);
        dst[3] = _YuvClamp(p0.r);
        dst[7] = _YuvClamp(p1.r);
        dst += 8;
    }
}

void yuvtoRGBA32_C(u8 *y, u8 *u, u8 *v, u8 *dst, u8 *end)
{
    YuvLut_t cu;
    YuvLut_t cv;
    YuvLut_t p0;
    YuvLut_t p1;

    while (dst < end) {
        cv = lutcr[*v++];
        cu = lutcb[*u++];
        _YuvLutAddARGB(&cu, &cv);
        p0 = luty[y[0]];
        p1 = luty[y[1]];
        y += 2;
        _YuvLutAddARGB(&p0, &cu);
        _YuvLutAddARGB(&p1, &cu);
        dst[0] = _YuvClamp(p0.b);
        dst[1] = _YuvClamp(p0.g);
        dst[2] = _YuvClamp(p0.r);
        dst[3] = _YuvClamp(p0.a);
        dst[4] = _YuvClamp(p1.b);
        dst[5] = _YuvClamp(p1.g);
        dst[6] = _YuvClamp(p1.r);
        dst[7] = _YuvClamp(p1.a);
        dst += 8;
    }
}

int YUV_convert_RGBA(u8 *y, u8 *u, u8 *v, int yStride, int width, int height, u8 *dst, int dstStride, int mode)
{
    int line;
    int lineBytes;
    int uvStride;
    u8 *pY;
    u8 *pU;
    u8 *pV;
    u8 *pDst;

    if (yStride & 1) {
        return 2;
    }
    if (dstStride & 7) {
        return 3;
    }
    pDst = dst;
    if ((u32)pDst & 7) {
        if ((u32)pDst & 3) {
            return 4;
        }
        pDst += 4;
        width--;
    }
    width &= ~1;
    if (width > 1 && height > 0) {
        line = 0;
        pY = y;
        pU = u;
        pV = v;
        lineBytes = width * 4;
        uvStride = yStride >> 1;
        for (; line < height; line++) {
            switch (mode) {
            case 0:
                yuvtoRGBA32_C(pY, pU, pV, pDst, pDst + lineBytes);
                break;
            case 1:
                yuvtoRGB32_C(pY, pU, pV, pDst, pDst + lineBytes);
                break;
            case 2:
                yuvtoA32_C(pY, pU, pV, pDst, pDst + lineBytes);
                break;
            }
            pY += yStride;
            if (line & 1) {
                pU += uvStride;
                pV += uvStride;
            }
            pDst += dstStride;
        }
    }
    return 0;
}
