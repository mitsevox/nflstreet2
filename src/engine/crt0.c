/* SN Systems libsn start-up code (libsn.a crt0.o): the program entry point the boot loader
   jumps to. It sets up the stack, small-data and small-data-2 registers, clears the paired-single
   quantisers and every floating-point register, zeroes .bss and .sbss, starts the SN debugger
   stub when the boot information asks for one, reads the command-line arguments the loader left,
   runs OSInit and DBInit, offers the pad-3 reset on development hardware, runs the static
   constructors and finally calls main and exit. With a debugger attached it first prints the
   libsn banner and drops into the debugger through an rfi with the trace bit set. Hand-written
   assembly. */

